const refNum = (p: Product) => Number((p.ref || '').replace(/\D/g, '')) || 0;

/** القطع الجاهزة الظاهرة، الأحدث أولًا حسب رقم القطعة */
export const readyPieces: Product[] = visibleProducts
  .filter((p) => p.availability === 'ready-piece' && p.ref)
  .sort((a, b) => refNum(b) - refNum(a));

export const readyGroupHref = (slug: string) => `/ready/${slug}/`;

export const readyGroupsWithItems = READY_GROUPS.map((g) => {
  const items = readyPieces.filter((p) => p.group === g.slug);
  return {
    ...g,
    items,
    count: items.length,
    minPrice: items.length ? Math.min(...items.map((p) => p.price)) : 0,
    maxPrice: items.length ? Math.max(...items.map((p) => p.price)) : 0,
    fees: Array.from(new Set(items.map((p) => p.deliveryFee ?? 0))).sort((a, b) => a - b),
    // صورة الغلاف من صور الموقع نفسه أولًا (لا Cloudinary): الدوائر والبانرات أعلى الصفحة،
    // وصورة من نطاق آخر تكلّف اتصالًا إضافيًا يؤخر LCP على الجوال.
    cover:
      items.flatMap((p) => p.images).find((src) => src.startsWith('/')) ?? items.find((p) => p.images[0])?.images[0],
  };
}).filter((g) => g.count > 0);
